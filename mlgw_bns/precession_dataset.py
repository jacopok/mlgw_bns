r"""Training sets of the regressed precession angles at scale.

:func:`~mlgw_bns.precession_regression.generate_training_set` holds a
training set in memory; :class:`ShardedDataset` keeps one on disk, in
shards, generated by any number of processes on any number of machines,
and resumable. A dataset is a directory::

    config.json            what the binaries are (DatasetConfig)
    shards/00000.npz       binaries 0 ... shard_size - 1, and so on
    shards/00000.json      when, where and how fast it was made
    locks/00000.lock       a shard being made: by whom, refreshed while it is
    refine/1/config.json   a refinement of the envelopes (refine_envelopes):
    refine/1/fold0.joblib  the regressors giving its priors, trained on the
    refine/1/shards/...    other folds, and the envelopes refitted with them

Shards are made, claimed and read as described in :mod:`mlgw_bns.sharding`:
in any order, by any process, and a shard lost is made again identically (to
the bit with the same batch of integrations: XLA vectorizes other batches
differently, which changes the angles by ~1e-17). The first ``N`` binaries
are a uniform sample of the
:class:`~mlgw_bns.precession_regression.TrainingRanges` for every ``N``: the
training sets of a learning curve are nested.

A shard has, for each binary, what
:func:`~mlgw_bns.precession_regression.generate_training_set` gives but the
nodes ``x``, which follow from the reference frequency
(:meth:`ShardedDataset.x`), and whether all of it is finite (``valid``):
some 65 kB a binary, 68 GB for :math:`2^{20}` binaries. Training reads only
the envelopes, the switch targets and the parameters, 15 kB a binary, one
shard at a time (:meth:`ShardedDataset.chunks`,
:meth:`~mlgw_bns.precession_regression.PrecessionRegressor.train_on_chunks`).
"""

from __future__ import annotations

import dataclasses
import json
import logging
import os
import time
from dataclasses import dataclass
from typing import Callable, Dict, Optional, Sequence

import numpy as np

from .batched_precession import N_STEPS
from .precession_regression import (
    AngleGrid,
    PrecessionRegressor,
    TrainingRanges,
    fit_all_envelopes,
    generate_training_set,
    integration_nodes,
)
from .sharding import ShardedStore, save_arrays, save_json, write_atomically

#: What a shard holds for each binary (``valid``: all of it is finite).
SHARD_FIELDS = (
    "intrinsic", "omega_reference", "switch", "coefficients", "baselines", "residuals",
    "zeta", "g", "valid",
)

#: What a refinement replaces of a shard.
REFINED_FIELDS = ("coefficients", "residuals")

#: What :meth:`PrecessionRegressor.train_on_chunks` reads, in order.
TRAINING_FIELDS = ("intrinsic", "omega_reference", "coefficients", "switch", "baselines")


@dataclass(frozen=True)
class DatasetConfig:
    """What the binaries of a :class:`ShardedDataset` are.

    Parameters
    ----------
    n_binaries : int
        How many; a dataset whose last shard is full can be grown.
    shard_size : int
        Binaries a shard.
    seed : int
        Shard ``k`` is drawn from the seed sequence ``(seed, k)``: datasets
        with different seeds are independent.
    grid, ranges
        The grid the envelopes are fitted on and the parameter space.
    n_steps, stride
        Of the integration (:func:`generate_training_set`).
    """

    n_binaries: int
    shard_size: int = 4096
    seed: int = 1
    grid: AngleGrid = AngleGrid()
    ranges: TrainingRanges = TrainingRanges()
    n_steps: int = N_STEPS
    stride: int = 2

    def to_json(self) -> str:
        return json.dumps(dataclasses.asdict(self), indent=2)

    @classmethod
    def from_json(cls, text: str) -> "DatasetConfig":
        values = json.loads(text)
        values["grid"] = AngleGrid(**values["grid"])
        values["ranges"] = TrainingRanges(
            **{k: tuple(v) if isinstance(v, list) else v for k, v in values["ranges"].items()}
        )
        return cls(**values)


class ShardedDataset(ShardedStore):
    """A training (or validation) set of the regressed precession angles on
    disk; see the module docstring. Open one with ``ShardedDataset(directory)``,
    make one with :meth:`create`."""

    config_class = DatasetConfig
    overlay_fields = REFINED_FIELDS

    # -- layout --------------------------------------------------------------

    def source_directory(self, source: str) -> str:
        """Where the shards of the envelopes of ``source`` are: ``"base"``
        (generated) or ``"refine<k>"``."""
        if source == "base":
            return self.directory
        return self.refinement_directory(_iteration(source))

    def refinement_directory(self, iteration: int) -> str:
        return os.path.join(self.directory, "refine", str(iteration))

    def parameters(self, index: int):
        """The intrinsic parameters and reference frequencies of shard ``index``."""
        return self.config.ranges.sample(self.shard_size(index), seed=self.seed(index))

    def x(self, omega_reference) -> np.ndarray:
        """The nodes of the angles ``zeta`` and ``g`` of binaries of these
        reference frequencies."""
        return integration_nodes(self.config.grid, omega_reference, self.config.n_steps, self.config.stride)

    # -- making shards -------------------------------------------------------

    def generate(
        self, n_jobs: int = -1, batch: int = 32, max_seconds: Optional[float] = None,
        stale_seconds: float = 600.0,
    ) -> bool:
        """Make the shards not yet there (see
        :meth:`~mlgw_bns.sharding.ShardedStore.work_through`), each with
        ``n_jobs`` processes integrating ``batch`` binaries at a time; whether
        all are there."""
        return super().generate(n_jobs, max_seconds, stale_seconds, batch=batch)

    def _make(self, index: int, n_jobs: int, batch: int = 32) -> tuple:
        config = self.config
        intrinsic, omega_reference = self.parameters(index)
        data = generate_training_set(
            config.grid, intrinsic, omega_reference, config.n_steps, config.stride, batch, n_jobs
        )
        del data["x"]
        valid = np.ones(len(intrinsic), bool)
        for value in data.values():
            valid &= np.all(np.isfinite(value.reshape(len(intrinsic), -1)), axis=1)
        largest = np.max(data["residuals"][valid], axis=0) if valid.any() else np.full(2, np.nan)
        arrays = dict(intrinsic=intrinsic, omega_reference=omega_reference, valid=valid, **data)
        return arrays, {"largest residuals": [float(r) for r in largest]}

    # -- reading -------------------------------------------------------------

    def chunks(self, n: Optional[int] = None, fields: Sequence[str] = TRAINING_FIELDS, source: str = "base",
               select: Optional[Callable[[np.ndarray], np.ndarray]] = None):
        """The ``fields`` of the first ``n`` valid binaries, a shard at a
        time (:meth:`~mlgw_bns.sharding.ShardedStore.chunks`); the envelopes
        (:data:`REFINED_FIELDS`) are those of ``source``."""
        return super().chunks(n, fields, source, select)

    def load(self, n: Optional[int] = None, fields: Sequence[str] = SHARD_FIELDS, source: str = "base",
             select=None) -> Dict[str, np.ndarray]:
        """:meth:`chunks`, concatenated."""
        return super().load(n, fields, source, select)

    def training_chunks(self, n: Optional[int] = None, source: str = "base", select=None) -> Callable:
        """What :meth:`PrecessionRegressor.train_on_chunks` takes, for the
        first ``n`` valid binaries."""
        return lambda: (
            tuple(chunk[name] for name in TRAINING_FIELDS)
            for chunk in self.chunks(n, TRAINING_FIELDS, source, select)
        )

    def train(self, n: Optional[int] = None, source: str = "base", **kwargs) -> PrecessionRegressor:
        """A :class:`PrecessionRegressor` trained on the first ``n`` valid
        binaries, a shard at a time; ``kwargs`` of
        :meth:`PrecessionRegressor.train_on_chunks`."""
        return PrecessionRegressor.train_on_chunks(
            self.training_chunks(n, source), grid=self.config.grid, ranges=self.config.ranges, **kwargs
        )

    # -- refinement ----------------------------------------------------------

    def refinement(self, iteration: int, folds: Optional[int] = None, prior_size: Optional[int] = None,
                   **train_kwargs) -> dict:
        """The settings of refinement ``iteration`` (``"refine<k>"``), set by
        the first call giving them: the binaries are split in ``folds`` (4)
        by their index, and the prior of those of each is the prediction of a
        regressor trained on the first ``prior_size`` (16384) of the others,
        with the envelopes of the previous iteration (or the base ones), with
        ``train_kwargs`` (of :meth:`PrecessionRegressor.train_on_chunks`,
        kernel ridge); see :func:`refine_envelopes`. Other settings than
        those set are refused."""
        filename = os.path.join(self.refinement_directory(iteration), "config.json")
        given = folds is not None or prior_size is not None or train_kwargs
        settings = json.loads(json.dumps({
            "folds": 4 if folds is None else folds,
            "prior_size": 16384 if prior_size is None else prior_size,
            "train": train_kwargs,
        }))
        if not os.path.exists(filename):
            if not given:
                raise FileNotFoundError(f"refinement {iteration} of {self.directory} has no settings yet")
            save_json(filename, settings)
        with open(filename) as file:
            stored = json.load(file)
        if given and stored != settings:
            raise ValueError(f"refinement {iteration} of {self.directory} was set up otherwise: {stored}")
        return stored

    def train_prior(self, iteration: int, fold: int) -> str:
        """Train (once) the regressor giving the priors of ``fold`` in
        refinement ``iteration``; its file."""
        import joblib

        settings = self.refinement(iteration)
        filename = os.path.join(self.refinement_directory(iteration), f"fold{fold}.joblib")
        if os.path.exists(filename):
            return filename
        folds = settings["folds"]
        previous = "base" if iteration == 1 else f"refine{iteration - 1}"
        start = time.time()
        regressor = PrecessionRegressor.train_on_chunks(
            self.training_chunks(settings["prior_size"], previous, lambda index: index % folds != fold),
            grid=self.config.grid, ranges=self.config.ranges,
            **{k: tuple(v) if isinstance(v, list) else v for k, v in settings["train"].items()},
        )
        write_atomically(filename, lambda file: joblib.dump(regressor, file))
        logging.info("refinement %i: prior of fold %i/%i in %.0f s", iteration, fold, folds, time.time() - start)
        return filename

    def refine(
        self, iteration: int, n_jobs: int = -1, max_seconds: Optional[float] = None,
        stale_seconds: float = 600.0,
    ) -> bool:
        """Refit the envelopes of the shards of refinement ``iteration`` not
        yet there, with the priors of :meth:`train_prior` (which must all be
        there); whether all are there."""
        settings = self.refinement(iteration)
        priors = [
            PrecessionRegressor.load(os.path.join(self.refinement_directory(iteration), f"fold{fold}.joblib"))
            for fold in range(settings["folds"])
        ]
        return self.work_through(
            f"refine{iteration}", lambda i: self._refit(i, iteration, priors, n_jobs), max_seconds, stale_seconds
        )

    def _refit(self, index: int, iteration: int, priors: list, n_jobs: int) -> None:
        start = time.time()
        with np.load(self.path(index)) as base:
            data = {name: base[name] for name in ("intrinsic", "omega_reference", "zeta", "g", "valid")}
        valid = np.flatnonzero(data["valid"])
        intrinsic, omega_reference = data["intrinsic"][valid], data["omega_reference"][valid]
        fold = (index * self.config.shard_size + valid) % len(priors)
        prior = np.empty((len(valid), self.config.grid.n_envelopes, self.config.grid.n_coefficients), complex)
        for f, regressor in enumerate(priors):
            prior[fold == f] = regressor.predict_coefficients(intrinsic[fold == f], omega_reference[fold == f])
        coefficients, residuals = fit_all_envelopes(
            self.config.grid, intrinsic, omega_reference, self.x(omega_reference),
            data["zeta"][valid], data["g"][valid], prior, n_jobs,
        )
        full_coefficients = np.full((len(data["valid"]),) + coefficients.shape[1:], np.nan + 0j)
        full_residuals = np.full((len(data["valid"]), 2), np.nan)
        full_coefficients[valid], full_residuals[valid] = coefficients, residuals
        save_arrays(self.path(index, f"refine{iteration}"), coefficients=full_coefficients, residuals=full_residuals)
        logging.info(
            "refinement %i, shard %i/%i: %i binaries in %.0f s, largest fit residuals %.1e (zeta) %.1e (G)",
            iteration, index, self.n_shards, len(valid), time.time() - start, *np.max(residuals, axis=0),
        )

def _iteration(source: str) -> int:
    if not source.startswith("refine"):
        raise ValueError(f"unknown source {source!r}: 'base' or 'refine<k>'")
    return int(source[len("refine"):])
